#!/usr/bin/env node
/**
 * Generate sw-assets.js: the service worker's precache list plus a content hash used as the
 * cache version, so every deploy that changes a file automatically invalidates the old cache.
 *
 *   npm run build:sw
 */
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, filter, out = []) {
  for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = path.posix.join(dir, e.name);
    if (e.isDirectory()) walk(rel, filter, out);
    else if (filter(rel)) out.push(rel);
  }
  return out;
}

export function collectPrecacheAssets() {
  const files = [
    'index.html',
    'manifest.json',
    'css/tailwind.output.css',
    'css/app.css',
    'fonts/inter-latin-wght-normal.woff2',
    ...walk('icons', f => /\.(svg|png)$/.test(f)),
    ...walk('src', f => f.endsWith('.js')),
    // Self-hosted libraries the app shell needs at boot. Shoelace components and icons are
    // runtime-cached on first use (there are thousands of them).
    ...walk('vendor', f => f.endsWith('.mjs')),
    'vendor/katex/katex.min.js',
    'vendor/katex/katex.min.css',
    'vendor/katex/contrib/mhchem.min.js',
    ...walk('vendor/katex/fonts', f => f.endsWith('.woff2')),
    'vendor/shoelace/shoelace-autoloader.js',
    'vendor/shoelace/themes/light.css',
    'vendor/shoelace/themes/dark.css'
  ].filter(f => fs.existsSync(path.join(root, f)));
  return [...new Set(files)].sort();
}

export function buildSwAssets() {
  const files = collectPrecacheAssets();
  const hash = crypto.createHash('sha256');
  for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
  hash.update(fs.readFileSync(path.join(root, 'sw.js')));
  const version = hash.digest('hex').slice(0, 12);
  return `// Generated by scripts/sw-manifest.mjs — do not edit by hand.\nself.KB_CACHE_VERSION = '${version}';\nself.KB_PRECACHE = ${JSON.stringify(['./', ...files.map(f => `./${f}`)], null, 2)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'sw-assets.js'), buildSwAssets());
  console.log('Wrote sw-assets.js');
}
